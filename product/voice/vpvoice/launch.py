# One runtime process per core behind one port. Python runs one core per process, and the audio path is CPU-bound
# (bench/results/: the event loop crosses 20 ms lag p99 between 25 and 35 calls per process), so a host carries
# calls by running more processes, each with its own admission cap (VP_MAX_CALLS_PER_PROCESS).
#
#   python -m vpvoice.launch                  # VP_WORKERS (default os.cpu_count()) workers + the front on $PORT
#   python -m vpvoice.launch --nginx-conf     # print the nginx config that routes media straight to the workers
#
# Why not SO_REUSEPORT: the kernel spreads connections at random, but a call is a ticket POST followed by a media
# socket (and carrier webhooks) that must reach the process holding that call. So:
#   - worker i listens on 127.0.0.1:VP_WORKER_BASE_PORT+i with VP_PUBLIC_URL=<public>/w/<i>, so every media and
#     webhook URL it hands out names it;
#   - the front (this process) takes the control routes: POST /v1/calls goes to the worker with the most free slots and,
#     on 503 at_capacity (refused before any record, so safe to resend), to the next; a retried ticket goes back to the
#     worker that accepted it (idempotency is per process); /v1/calls/{id}[/end|/listen|/whisper|/takeover] go to the
#     owner; /v1/health sums them;
#   - /w/<i>/... is proxied to worker i. The front can proxy media sockets itself (development, one-container), but
#     that puts every audio frame through one more Python process: in production route /w/<i>/ in nginx or the ingress
#     (--nginx-conf), and point / at the front on VP_FRONT_PORT.
# A worker that dies is restarted (its calls are lost, as in a single process); SIGTERM stops them all, and each ends
# its calls with call.ended on the way out.
import argparse, asyncio, json, logging, os, signal, sys, time

import aiohttp
from aiohttp import web

log = logging.getLogger('vpvoice.launch')
HOP = {'host', 'connection', 'keep-alive', 'transfer-encoding', 'upgrade', 'content-length', 'proxy-connection', 'te', 'trailer', 'content-encoding'}
OWNER_TTL_S = 6 * 3600
TASKS = web.AppKey('tasks', list)


def settings(env):
    port = int(env.get('PORT') or 8080)
    n = int(env.get('VP_WORKERS') or os.cpu_count() or 1)
    base = int(env.get('VP_WORKER_BASE_PORT') or port + 1)
    return port, n, base, (env.get('VP_PUBLIC_URL') or '').rstrip('/')


def nginx_conf(env):
    port, n, base, _ = settings(env)
    front = int(env.get('VP_FRONT_PORT') or base + n)
    ws = ('proxy_http_version 1.1; proxy_set_header Upgrade $http_upgrade; proxy_set_header Connection $connection_upgrade; '
          'proxy_read_timeout 3h; proxy_buffering off;')
    workers = '\n'.join(f'    location /w/{i}/ {{ proxy_pass http://127.0.0.1:{base + i}/; {ws} }}' for i in range(n))
    return f'''# generated by python -m vpvoice.launch --nginx-conf ({n} workers); run the launcher with VP_FRONT_PORT={front}
map $http_upgrade $connection_upgrade {{ default upgrade; '' close; }}
server {{
    listen {port};
    client_max_body_size 2m;
{workers}
    location / {{ proxy_pass http://127.0.0.1:{front}; proxy_http_version 1.1; proxy_set_header Connection ""; }}
}}
'''


class Front:
    def __init__(self, n, base, cmd, env, poll_s=1.0):
        self.n, self.base, self.cmd, self.env, self.poll_s = n, base, cmd, env, poll_s
        self.procs = [None] * n; self.health = [None] * n; self.since = [0] * n; self.rr = 0; self.owners = {}; self.http = None; self.stopping = False

    def url(self, i, path): return f'http://127.0.0.1:{self.base + i}{path}'

    # ------------------------------------------------------------ workers
    def spawn(self, i, public):
        env = {**self.env, 'PORT': str(self.base + i), 'VP_BIND': '127.0.0.1', 'VP_WORKER_ID': f'w{i}',
               'VP_PUBLIC_URL': f'{public}/w/{i}' if public else ''}
        argv = [a.replace('{port}', str(self.base + i)) for a in self.cmd]
        return asyncio.create_subprocess_exec(*argv, env=env)

    async def supervise(self, public):
        backoff = [1.0] * self.n
        async def keep(i):
            while not self.stopping:
                self.procs[i] = await self.spawn(i, public); started = time.monotonic()
                code = await self.procs[i].wait(); self.health[i] = None
                if self.stopping: return
                backoff[i] = 1.0 if time.monotonic() - started > 30 else min(30.0, backoff[i] * 2)
                log.error('worker w%d exited with %s; restarting in %.0f s', i, code, backoff[i])
                await asyncio.sleep(backoff[i])
        await asyncio.gather(*(keep(i) for i in range(self.n)))

    async def poll(self):
        while not self.stopping:
            for i in range(self.n):
                seen = self.since[i]                       # placements before this poll are in its count; later ones are not
                try:
                    async with self.http.get(self.url(i, '/v1/health'), timeout=aiohttp.ClientTimeout(total=2)) as r:
                        self.health[i] = await r.json() if r.status == 200 else None
                    self.since[i] -= seen
                except Exception:
                    self.health[i] = None
            now = time.monotonic()
            for cid, (_, at) in list(self.owners.items()):
                if now - at > OWNER_TTL_S: self.owners.pop(cid, None)
            await asyncio.sleep(self.poll_s)

    async def stop(self):
        self.stopping = True
        for p in self.procs:
            if p and p.returncode is None: p.send_signal(signal.SIGTERM)
        for p in self.procs:
            if p:
                try: await asyncio.wait_for(p.wait(), 20)
                except asyncio.TimeoutError: p.kill()

    # ------------------------------------------------------------ forwarding
    async def forward(self, i, req, body, path=None):
        hdr = {k: v for k, v in req.headers.items() if k.lower() not in HOP}
        async with self.http.request(req.method, self.url(i, path or req.path_qs), data=body, headers=hdr, allow_redirects=False) as r:
            out = await r.read()
            return r.status, web.Response(body=out, status=r.status, headers={k: v for k, v in r.headers.items() if k.lower() not in HOP})

    def order(self):
        """Most free slots first (the last poll, less what this front placed since); ties in turn; unknown workers last."""
        def free(i):
            h = self.health[i]
            return h['capacity']['free'] - self.since[i] if h and 'capacity' in h else -10 ** 6
        self.rr = (self.rr + 1) % self.n
        return sorted(range(self.n), key=lambda i: (-free(i), (i - self.rr) % self.n))

    async def create_call(self, req):
        body = await req.read()
        try: cid = json.loads(body).get('conversationId')
        except Exception: cid = None
        own = self.owners.get(cid) if isinstance(cid, str) else None
        tried = [own[0]] if own else self.order()
        last = None
        for i in tried:
            self.since[i] += 1                            # reserve before awaiting, so concurrent tickets spread
            try:
                st, resp = await self.forward(i, req, body)
            except aiohttp.ClientError:
                self.since[i] -= 1; continue              # a worker restarting: nothing was placed there
            if st != 202: self.since[i] -= 1
            if st == 503 and b'"at_capacity"' in resp.body:
                last = resp; continue                     # refused before any record: the next worker may take it
            if st == 202 and cid: self.owners[cid] = (i, time.monotonic())
            return resp
        if last is not None:
            return last                                    # every worker is full: the dialer backs off (Retry-After)
        return web.json_response({'error': 'unavailable', 'message': 'no runtime worker answered', 'placed': False}, status=503,
                                 headers={'Retry-After': '5'})

    async def call_route(self, req):
        body = await req.read(); cid = req.match_info['id']
        own = self.owners.get(cid)
        for i in ([own[0]] if own else range(self.n)):
            try: st, resp = await self.forward(i, req, body)
            except aiohttp.ClientError: continue
            if st != 404 or own: return resp               # a call lives on one worker; the others say 404
        return web.json_response({'error': 'not_found', 'message': 'no such call'}, status=404)

    async def health_route(self, req):
        up = [h for h in self.health if h]
        cap = {k: sum(h['capacity'][k] for h in up) for k in ('admitted', 'max', 'free')} if up else {'admitted': 0, 'max': 0, 'free': 0}
        first = up[0] if up else {}
        return web.json_response({'ok': len(up) == self.n, 'runtimeVersion': first.get('runtimeVersion'), 'signing': first.get('signing'),
                                  'control': first.get('control'), 'stacks': first.get('stacks', {}), 'activeCalls': sum(h['activeCalls'] for h in up),
                                  'capacity': cap, 'workers': [{'worker': f'w{i}', 'up': bool(h), **({'capacity': h['capacity']} if h else {})}
                                                               for i, h in enumerate(self.health)]},
                                 status=200 if up else 503)

    async def worker_route(self, req):
        i = int(req.match_info['i'])
        if not 0 <= i < self.n: raise web.HTTPNotFound()
        path = '/' + req.match_info['tail'] + (('?' + req.query_string) if req.query_string else '')
        if req.headers.get('upgrade', '').lower() == 'websocket':
            return await self.proxy_ws(i, req, path)
        st, resp = await self.forward(i, req, await req.read(), path)
        return resp

    async def proxy_ws(self, i, req, path):
        try:
            up = await self.http.ws_connect(self.url(i, path).replace('http://', 'ws://'), max_msg_size=4 * 1024 * 1024)
        except aiohttp.WSServerHandshakeError as e:
            raise web.HTTPForbidden() if e.status == 403 else web.HTTPBadGateway()
        down = web.WebSocketResponse(max_msg_size=4 * 1024 * 1024); await down.prepare(req)

        async def pump(a, b):
            async for m in a:
                if m.type == aiohttp.WSMsgType.TEXT: await b.send_str(m.data)
                elif m.type == aiohttp.WSMsgType.BINARY: await b.send_bytes(m.data)
                else: break
            await b.close()
        try: await asyncio.gather(pump(down, up), pump(up, down), return_exceptions=True)
        finally: await up.close()
        return down

    def app(self, public):
        a = web.Application(client_max_size=2 * 1024 * 1024)
        a.router.add_post('/v1/calls', self.create_call)
        a.router.add_post('/v1/calls/{id}/end', self.call_route)
        a.router.add_post('/v1/calls/{id}/{action:listen|whisper|takeover}', self.call_route)
        a.router.add_get('/v1/calls/{id}', self.call_route)
        a.router.add_get('/v1/health', self.health_route)
        a.router.add_route('*', r'/w/{i:\d+}/{tail:.*}', self.worker_route)

        async def startup(app):
            self.http = aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=30))
            app[TASKS] = [asyncio.ensure_future(self.supervise(public)), asyncio.ensure_future(self.poll())]

        async def shutdown(app):
            await self.stop()
            for t in app[TASKS]: t.cancel()
            await self.http.close()
        a.on_startup.append(startup); a.on_shutdown.append(shutdown)
        return a


def main(argv=None):
    ap = argparse.ArgumentParser(prog='python -m vpvoice.launch')
    ap.add_argument('--nginx-conf', action='store_true', help='print the nginx config for routing /w/<i>/ to the workers')
    ap.add_argument('worker_cmd', nargs=argparse.REMAINDER, help='after --: the worker command ({port} is replaced); default: python -m vpvoice')
    a = ap.parse_args(argv)
    if a.worker_cmd[:1] == ['--']: a.worker_cmd = a.worker_cmd[1:]
    env = dict(os.environ)
    if a.nginx_conf: print(nginx_conf(env)); return
    logging.basicConfig(level=env.get('VP_LOG_LEVEL', 'INFO'), format='%(asctime)s %(levelname)s %(name)s %(message)s')
    port, n, base, public = settings(env)
    listen = int(env.get('VP_FRONT_PORT') or port)
    front = Front(n, base, a.worker_cmd or [sys.executable, '-m', 'vpvoice'], env)
    log.info('%d workers on 127.0.0.1:%d-%d, front on %d, cap %s per worker', n, base, base + n - 1, listen, env.get('VP_MAX_CALLS_PER_PROCESS') or 20)
    web.run_app(front.app(public), host=env.get('VP_BIND') or '0.0.0.0', port=listen, print=None)


if __name__ == '__main__':
    main()
